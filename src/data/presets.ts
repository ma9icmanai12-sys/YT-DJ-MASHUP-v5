/**
 * Harmonic Mixing Key Compatibility Calculator (Camelot System)
 */
export function checkKeyCompatibility(keyA: string, keyB: string): { match: boolean; type: string } {
  if (!keyA || !keyB) return { match: false, type: 'Unknown' };

  const extractCamelot = (k: string) => {
    const match = k.match(/(\d{1,2})([AB])/i);
    if (!match) return null;
    return { num: parseInt(match[1], 10), letter: match[2].toUpperCase() };
  };

  const cA = extractCamelot(keyA);
  const cB = extractCamelot(keyB);

  if (!cA || !cB) return { match: false, type: 'Standard' };

  if (cA.num === cB.num && cA.letter === cB.letter) {
    return { match: true, type: 'Perfect Key (Same Tone)' };
  }

  // Same number, relative major/minor swap (e.g. 8A <-> 8B)
  if (cA.num === cB.num && cA.letter !== cB.letter) {
    return { match: true, type: 'Relative Key (Major/Minor)' };
  }

  // +1 or -1 on Camelot wheel
  const numDiff = Math.abs(cA.num - cB.num);
  if (cA.letter === cB.letter && (numDiff === 1 || numDiff === 11)) {
    return { match: true, type: 'Harmonic Step (+/- 1 on Wheel)' };
  }

  return { match: false, type: 'Key Shift Needed' };
}
